#!/usr/bin/env node
/**
 * .planning/audit/tools/gen-prod-schema.mjs
 *
 * Assembles `.planning/audit/schema/prod.schema.sql` from the SELECT-only catalog
 * captures in `.planning/audit/raw/prod/`.
 *
 * WHY THIS EXISTS
 * ---------------
 * AUDIT-01 asks for a committed production schema snapshot. The canonical way to
 * produce one is `supabase db dump`, which needs a Postgres connection string. No
 * connection string was ever supplied to this phase: the operator resolved the
 * credential checkpoint by authenticating the Supabase MCP server (Management API)
 * instead, which can run SELECTs but cannot hand a URI to `pg_dump`. See
 * `.planning/audit/schema/prod.schema.sql`'s header for the exact command to run
 * once a connection string exists.
 *
 * So this is a CATALOG-DERIVED snapshot: every statement below is reconstructed
 * from `information_schema` and `pg_catalog` rows that were read with SELECT. It is
 * NOT a pg_dump, it is not guaranteed to restore, and it must never be fed to
 * `psql` against a live database. It exists to be READ and DIFFED.
 *
 * READ-ONLY CONTRACT
 * ------------------
 * This script performs no network I/O and opens no database connection. It reads
 * JSON from `raw/prod/` and writes one file under `.planning/audit/schema/`.
 * It never reads an environment variable, so it cannot leak one.
 *
 * DETERMINISM
 * -----------
 * Every collection is sorted before emission so that re-running against the same
 * captures is byte-identical, and a re-capture produces a reviewable diff rather
 * than a reshuffle.
 *
 * Usage:
 *   node .planning/audit/tools/gen-prod-schema.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const RAW = '.planning/audit/raw/prod';
const OUT = '.planning/audit/schema/prod.schema.sql';

const read = (name) => JSON.parse(readFileSync(join(RAW, `${name}.json`), 'utf8'));
const by = (...keys) => (a, b) => {
  for (const k of keys) {
    const x = a[k], y = b[k];
    if (x === y) continue;
    if (typeof x === 'number' && typeof y === 'number') return x - y;
    return String(x) < String(y) ? -1 : 1;
  }
  return 0;
};

const manifest = read('MANIFEST');
const identity = read('transport-identity').rows[0];
const columns = read('information-schema-columns').rows.slice().sort(by('table_name', 'ordinal_position'));
const tables = read('tables').rows.slice().sort(by('schema', 'name'));
const constraints = read('constraints').rows.slice().sort(by('table', 'conname'));
const indexes = read('indexes').rows.slice().sort(by('tablename', 'indexname'));
const functions = read('functions').rows.slice().sort(by('name', 'args'));
const triggers = read('triggers').rows.slice().sort(by('schema', 'table', 'tgname'));
const views = read('views').rows.slice().sort(by('name'));
const sequences = read('sequences').rows.slice().sort(by('sequence_name'));
const grants = read('grants').rows.slice().sort(by('table_schema', 'table_name', 'grantee'));
const policies = read('pg-policies').rows.slice().sort(by('schemaname', 'tablename', 'policyname'));
const buckets = read('storage-buckets').rows.slice().sort(by('name'));
const cronJobs = read('cron-job').rows.slice().sort(by('jobid'));
const extensions = read('extensions').rows.filter((e) => e.installed_version).slice().sort(by('name'));
const migrations = read('migrations-applied').rows.slice().sort(by('version'));
const rowCounts = read('row-counts').rows.slice().sort(by('table'));

const out = [];
const w = (line = '') => out.push(line);
const section = (title) => {
  w();
  w('-- ' + '='.repeat(74));
  w(`-- ${title}`);
  w('-- ' + '='.repeat(74));
  w();
};

/* ------------------------------------------------------------------ types -- */

/** Rebuild a column's SQL type from the information_schema row. */
function sqlType(c) {
  if (c.data_type === 'ARRAY') {
    // udt_name for an array is the element type prefixed with '_'
    return `${c.udt_name.replace(/^_/, '')}[]`;
  }
  if (c.data_type === 'USER-DEFINED') return c.udt_name;
  if (c.character_maximum_length) return `${c.data_type}(${c.character_maximum_length})`;
  if (c.data_type === 'numeric' && c.numeric_precision != null) {
    return `numeric(${c.numeric_precision},${c.numeric_scale ?? 0})`;
  }
  return c.data_type;
}

function columnLine(c) {
  const parts = [`    ${c.column_name}`, sqlType(c)];
  if (c.is_generated === 'ALWAYS' && c.generation_expression) {
    parts.push(`GENERATED ALWAYS AS (${c.generation_expression}) STORED`);
  }
  if (c.is_identity === 'YES') parts.push('GENERATED BY DEFAULT AS IDENTITY');
  if (c.column_default != null) parts.push(`DEFAULT ${c.column_default}`);
  if (c.is_nullable === 'NO') parts.push('NOT NULL');
  return parts.join(' ');
}

/* ----------------------------------------------------------------- header -- */

w('--');
w('-- catalog-derived snapshot via Management API SELECTs, not pg_dump; see raw/prod/MANIFEST.json');
w('--');
w('-- .planning/audit/schema/prod.schema.sql');
w('--');
w('-- Requirement: AUDIT-01 (live schema snapshots: production, staging, local)');
w('-- Plan:        01-06');
w('-- Date:        2026-09-14');
w('--');
w('-- WHAT THIS IS');
w('--   A reconstruction of the production schema from catalog rows that were read with');
w('--   SELECT statements only. Every object below was derived from information_schema or');
w('--   pg_catalog, captured through the Supabase MCP server (Management API) and stored');
w('--   verbatim in .planning/audit/raw/prod/. Each raw envelope carries the exact SQL that');
w('--   produced it in its `query` field; that is the citation for everything here.');
w('--');
w('-- WHAT THIS IS NOT');
w('--   This is NOT a pg_dump. It is not ordered for restore, it omits object attributes');
w('--   that only pg_dump knows, and it must never be replayed against a database. It is a');
w('--   reading and diffing artifact. Treat any attempt to execute it as a defect.');
w('--');
w('-- WHY NOT A DUMP');
w('--   `supabase db dump` requires a Postgres connection string. None was supplied to this');
w('--   phase: the operator resolved the credential checkpoint by authenticating the Supabase');
w('--   MCP server rather than exporting a token or a URI, and MCP can run SELECTs but cannot');
w('--   hand a URI to pg_dump. The container daemon (OrbStack, server 29.4.0) was running, so');
w('--   the daemon was not the blocker — the missing connection string was.');
w('--');
w('-- TO PRODUCE THE CANONICAL DUMP, once a connection string exists (exported into the');
w('-- shell only, never written to a file and never passed as a CLI argument):');
w('--');
w('--     supabase db dump --db-url "$PROD_DB_URL" \\');
w('--       --schema public,storage \\');
w('--       -f .planning/audit/schema/prod.schema.sql');
w('--');
w('--     bash .planning/audit/tools/readonly-guard.sh');
w('--');
w('--   The `auth` schema is deliberately excluded: an auth dump can carry role grants and');
w('--   inline keys into git history permanently, and .planning/ is committed. Never pass');
w('--   --role-only into a committed path. For the same reason this file contains no auth');
w('--   object: the auth schema was observed only as a table-name list');
w('--   (raw/prod/auth-config-tables.json, 23 names, no columns and no grants).');
w('--');
w('-- REGENERATE THIS FILE (no database access; reads raw/prod/ only):');
w('--     node .planning/audit/tools/gen-prod-schema.mjs');
w('--');
w('-- TRANSPORT IDENTITY (raw/prod/transport-identity.json)');
w(`--   project             ${manifest.project}`);
w(`--   project_ref         ${manifest.project_ref}   <- redacted at capture time`);
w(`--   transport           ${manifest.transport}`);
w(`--   role                ${identity.role}`);
w(`--   database            ${identity.db}`);
w(`--   server_version      ${identity.server_version}`);
w(`--   transaction_read_only  ${identity.txn_read_only}   <- see the caveat below`);
w(`--   captured            ${manifest.capture_started_at} .. ${manifest.capture_finished_at}`);
w(`--   captures            ${manifest.capture_count}, failures ${manifest.failed_queries.length}, redactions ${manifest.total_redactions}`);
w('--');
w('-- READ-ONLY CAVEAT, recorded rather than glossed');
w('--   `transaction_read_only` is `off` and the role is `postgres`. The MCP transport does');
w('--   NOT enforce read-only server-side, which is what the plan specified and what');
w('--   tools/sql-readonly.mjs implements for the Management API path it was built for. The');
w('--   safeguard actually in force during this capture was SELECT-only discipline: every one');
w('--   of the 20 statements is a SELECT, each is recorded verbatim in its raw envelope, and');
w('--   all 20 succeeded. No DDL and no DML was issued. A reviewer can verify this claim by');
w('--   reading the `query` field of every file in raw/prod/ — that is why they are committed.');
w('--');
w('-- SCOPE');
w('--   public schema: all objects below. storage schema: buckets and policies only.');
w('--   cron schema: the job inventory only. auth schema: excluded entirely.');
w('--');

/* ------------------------------------------------------------- extensions -- */

section(`INSTALLED EXTENSIONS (${extensions.length} installed of ${read('extensions').row_count} available)`);
w('-- Informational. Emitted as comments because extension installation is an operator');
w('-- action, not part of a schema diff. Source: raw/prod/extensions.json (list_extensions).');
w();
for (const e of extensions) {
  w(`--   ${e.name.padEnd(28)} ${String(e.installed_version).padEnd(12)} schema=${e.schema ?? '-'}`);
}

/* ------------------------------------------------------------------ types -- */

section('USER-DEFINED TYPES');
const udts = [...new Set(columns.filter((c) => c.data_type === 'USER-DEFINED' || (c.data_type === 'ARRAY' && !c.udt_name.match(/^_(text|int[248]|float[48]|bool|uuid|jsonb?|timestamptz|timestamp|date|numeric|bytea)$/)))
  .map((c) => c.udt_name.replace(/^_/, '')))].sort();
if (udts.length === 0) {
  w('-- none referenced by any public column');
} else {
  w('-- NOT CAPTURED: no pg_type/pg_enum query was issued during this capture, so the label');
  w('-- lists of these types are unknown. This is a real gap in the snapshot, recorded rather');
  w('-- than guessed. Recover with:');
  w('--   select t.typname, e.enumlabel, e.enumsortorder from pg_type t');
  w('--     join pg_enum e on e.enumtypid = t.oid order by 1, 3;');
  w();
  for (const t of udts) {
    const users = columns.filter((c) => c.udt_name.replace(/^_/, '') === t)
      .map((c) => `${c.table_name}.${c.column_name}`).sort();
    w(`-- CREATE TYPE public.${t} AS ENUM (...labels not captured...);   -- used by: ${users.join(', ')}`);
  }
}

/* ----------------------------------------------------------------- tables -- */

const publicTables = tables.filter((t) => t.schema === 'public' && (t.relkind === 'r' || t.relkind === 'p'))
  .map((t) => t.name).sort();

section(`TABLES — public (${publicTables.length} tables, ${columns.length} columns)`);
w('-- Source: raw/prod/information-schema-columns.json, ordered by table then ordinal_position.');
w('-- Constraints are emitted separately below so that foreign keys do not depend on table order.');

for (const name of publicTables) {
  const cols = columns.filter((c) => c.table_name === name);
  const meta = tables.find((t) => t.schema === 'public' && t.name === name);
  const approx = rowCounts.find((r) => r.table === name);
  w();
  w(`-- ${name}: ${cols.length} columns, RLS ${meta?.rls_enabled ? 'ENABLED' : 'DISABLED'}${meta?.rls_forced ? ' (FORCED)' : ''}${approx ? `, ~${approx.approx_rows} live rows` : ''}`);
  w(`CREATE TABLE public.${name} (`);
  w(cols.map(columnLine).join(',\n'));
  w(');');
  if (meta?.comment) w(`COMMENT ON TABLE public.${name} IS ${JSON.stringify(meta.comment)};`);
}

/* ------------------------------------------------------------ constraints -- */

const CONTYPE = { p: 'PRIMARY KEY', u: 'UNIQUE', f: 'FOREIGN KEY', c: 'CHECK' };
const counts = {};
for (const c of constraints) counts[c.contype] = (counts[c.contype] || 0) + 1;

section(`CONSTRAINTS — public (${constraints.length}: ${Object.keys(CONTYPE).filter((k) => counts[k]).map((k) => `${counts[k]} ${CONTYPE[k].toLowerCase()}`).join(', ')})`);
w('-- Source: raw/prod/constraints.json — pg_get_constraintdef(oid, true), emitted verbatim.');
w('-- Foreign keys into auth.users are shown as captured; the auth schema itself is excluded.');
w();
for (const c of constraints) {
  w(`ALTER TABLE ONLY public.${c.table} ADD CONSTRAINT ${c.conname} ${c.definition};`);
}

/* ---------------------------------------------------------------- indexes -- */

const constraintBacked = new Set(constraints.filter((c) => c.contype === 'p' || c.contype === 'u').map((c) => c.conname));
const standalone = indexes.filter((i) => !constraintBacked.has(i.indexname));
const backing = indexes.filter((i) => constraintBacked.has(i.indexname));

section(`INDEXES — public (${indexes.length} total: ${standalone.length} standalone, ${backing.length} constraint-backed)`);
w('-- Source: raw/prod/indexes.json — pg_indexes.indexdef, emitted verbatim.');
w('-- Constraint-backed indexes are listed as comments: they are created by the ALTER TABLE');
w('-- ADD CONSTRAINT statements above, and repeating them as CREATE INDEX would double-count.');
w();
for (const i of standalone) w(`${i.indexdef};`);
w();
for (const i of backing) w(`--  (constraint-backed) ${i.indexdef};`);

/* -------------------------------------------------------------- functions -- */

section(`FUNCTIONS — public (${functions.length})`);
w('-- Source: raw/prod/functions.json — pg_get_functiondef(oid), emitted verbatim.');
w('-- SECURITY DEFINER functions run with the definer\'s privileges and bypass the caller\'s');
w('-- RLS. They are called out per function below; plan 01-09 owns the authorization review.');
const secdef = functions.filter((f) => f.security_definer);
w(`-- ${secdef.length} of ${functions.length} are SECURITY DEFINER.`);
for (const f of functions) {
  w();
  w(`-- public.${f.name}(${f.args}) — ${f.language}${f.security_definer ? ', SECURITY DEFINER' : ', SECURITY INVOKER'}, volatility=${f.provolatile}`);
  w(`${f.definition.trimEnd()};`);
}

/* --------------------------------------------------------------- triggers -- */

section(`TRIGGERS (${triggers.length})`);
w('-- Source: raw/prod/triggers.json — pg_get_triggerdef(oid, true), internal triggers excluded.');
w();
for (const t of triggers) {
  w(`-- ${t.schema}.${t.table} — enabled=${t.tgenabled}`);
  w(`${t.definition};`);
}

/* ------------------------------------------------------------------ views -- */

section(`VIEWS AND MATERIALIZED VIEWS — public (${views.length})`);
if (views.length === 0) {
  w('-- none. The query in raw/prod/views.json returned 0 rows: production has no view and no');
  w('-- materialized view in the public schema. Recorded as a positive observation, because');
  w('-- "no views" and "views were never queried" are different facts.');
} else {
  for (const v of views) {
    w();
    w(`CREATE ${v.relkind === 'm' ? 'MATERIALIZED ' : ''}VIEW public.${v.name} AS`);
    w(`${v.definition.trimEnd()};`);
  }
}

/* -------------------------------------------------------------- sequences -- */

section(`SEQUENCES — public (${sequences.length})`);
if (sequences.length === 0) {
  w('-- none. raw/prod/sequences.json returned 0 rows, and no public column is an identity');
  w('-- column. Every primary key in this schema is a uuid with a gen_random_uuid() or');
  w('-- uuid_generate_v4() default; there is no serial anywhere.');
} else {
  for (const s of sequences) {
    w(`CREATE SEQUENCE public.${s.sequence_name} AS ${s.data_type} START WITH ${s.start_value} INCREMENT BY ${s.increment};`);
  }
}

/* -------------------------------------------------- row level security --- */

const rlsOn = tables.filter((t) => t.schema === 'public' && t.rls_enabled).map((t) => t.name).sort();
const rlsOff = publicTables.filter((n) => !rlsOn.includes(n));

section(`ROW LEVEL SECURITY — public (${rlsOn.length} of ${publicTables.length} tables enabled)`);
w('-- Source: raw/prod/tables.json — pg_class.relrowsecurity / relforcerowsecurity.');
if (rlsOff.length) {
  w(`-- RLS NOT ENABLED on: ${rlsOff.join(', ')}  <- review these first`);
} else {
  w('-- RLS is enabled on every public table. Enablement is necessary but not sufficient:');
  w('-- a table with RLS on and a permissive USING (true) policy is open. Plan 01-09 owns');
  w('-- the policy-effectiveness review; this file records enablement only.');
}
w();
for (const name of rlsOn) w(`ALTER TABLE public.${name} ENABLE ROW LEVEL SECURITY;`);

/* --------------------------------------------------------------- policies -- */

for (const schema of ['public', 'storage']) {
  const rows = policies.filter((p) => p.schemaname === schema);
  section(`POLICIES — ${schema} (${rows.length})`);
  w(`-- Source: raw/prod/pg-policies.json — pg_policies, emitted verbatim from qual/with_check.`);
  w('-- Reconstructed as CREATE POLICY for readability; the authoritative rows are the raw JSON.');
  let currentTable = null;
  for (const p of rows) {
    if (p.tablename !== currentTable) { currentTable = p.tablename; w(); w(`-- ${schema}.${currentTable}`); }
    const roles = String(p.roles).replace(/^\{|\}$/g, '').split(',').filter(Boolean).join(', ');
    const lines = [`CREATE POLICY ${JSON.stringify(p.policyname)} ON ${schema}.${p.tablename}`];
    lines.push(`    AS ${p.permissive} FOR ${p.cmd} TO ${roles || 'public'}`);
    if (p.qual != null) lines.push(`    USING (${p.qual})`);
    if (p.with_check != null) lines.push(`    WITH CHECK (${p.with_check})`);
    w(lines.join('\n') + ';');
  }
}

/* ----------------------------------------------------------------- grants -- */

section(`TABLE GRANTS — public and storage (${grants.length} grantee/table pairs)`);
w('-- Source: raw/prod/grants.json — information_schema.role_table_grants, privileges aggregated.');
w('-- Grantees restricted to anon, authenticated, service_role, postgres, public. No');
w('-- supabase_auth_admin grant is captured here: the auth schema is out of scope by design.');
w('--');
w('-- Read these against the RLS section above. A broad table grant to `anon` is only as');
w('-- restrictive as the policies on that table; AUDIT-09/AUDIT-10 (plan 01-09) reconcile them.');
w();
for (const g of grants) {
  w(`GRANT ${g.privileges} ON ${g.table_schema}.${g.table_name} TO ${g.grantee};`);
}

/* ---------------------------------------------------------------- storage -- */

section(`STORAGE BUCKETS (${buckets.length})`);
w('-- Source: raw/prod/storage-buckets.json — rows of storage.buckets. These are configuration');
w('-- rows, not DDL, so they are emitted as an inventory. `public: true` means objects are');
w('-- readable without a signed URL; plan 01-10 owns the storage exposure review.');
w();
for (const b of buckets) {
  w(`--   ${b.name.padEnd(20)} public=${String(b.public).padEnd(6)} size_limit=${b.file_size_limit ?? 'none'}  mime=${b.allowed_mime_types ?? 'any'}`);
}

/* ------------------------------------------------------------------- cron -- */

section(`SCHEDULED JOBS — cron.job (${cronJobs.length})`);
w('-- Source: raw/prod/cron-job.json. Emitted as an inventory; pg_cron jobs are rows, not DDL.');
w('-- Every command below is plain SQL calling a public function — none of them issues an HTTP');
w('-- request, so no cron job in production invokes an application endpoint. Plan 01-10 owns');
w('-- the cron review and raw/prod/cron-job-run-details.json holds the last 100 run outcomes.');
w();
for (const j of cronJobs) {
  w(`--   [${j.jobid}] ${String(j.jobname).padEnd(24)} ${String(j.schedule).padEnd(14)} active=${j.active}  ${j.command}`);
}

/* ------------------------------------------------------------- migrations -- */

section(`APPLIED MIGRATIONS (${migrations.length} applied on production)`);
w('-- Source: raw/prod/migrations-applied.json (list_migrations).');
w(`-- The repository tracks 44 files under supabase/migrations/; production reports`);
w(`-- ${migrations.length} applied versions. The counts do not agree. That discrepancy is a`);
w('-- finding candidate for AUDIT-02 (plan 01-08), not something this file resolves.');
w();
w('--   ' + migrations.map((m) => m.version).join(', '));

/* ----------------------------------------------------------------- footer -- */

section('END OF SNAPSHOT');
w(`-- ${publicTables.length} tables, ${columns.length} columns, ${constraints.length} constraints, ${indexes.length} indexes,`);
w(`-- ${functions.length} functions, ${triggers.length} triggers, ${views.length} views, ${sequences.length} sequences,`);
w(`-- ${policies.length} policies, ${grants.length} grants, ${buckets.length} storage buckets, ${cronJobs.length} cron jobs.`);
w('--');
w('-- Generated by .planning/audit/tools/gen-prod-schema.mjs from .planning/audit/raw/prod/.');
w('-- No database connection was opened by the generator.');

writeFileSync(OUT, out.join('\n').replace(/\n{3,}/g, '\n\n') + '\n');
process.stdout.write(`${OUT} written\n`);
